const {readFileSync} = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const {webcrypto} = require('node:crypto');
const nodes = new Map();
const node = () => ({value:'',innerHTML:'',textContent:'',hidden:false,classList:{toggle(){}},addEventListener(){},querySelectorAll(){return []},focus(){}});
const context=vm.createContext({crypto:webcrypto,TextEncoder,structuredClone,console,setTimeout:()=>0,clearTimeout(){},localStorage:{getItem(){return null},setItem(){}},document:{querySelector(s){if(!nodes.has(s))nodes.set(s,node());return nodes.get(s)},querySelectorAll(){return []},addEventListener(){}}});
vm.runInContext(readFileSync(require('node:path').join(__dirname,'../dist/app.js'),'utf8'),context);
vm.runInContext(`
const assert = (x,m) => {if(!x)throw Error(m)};
state = initial();
const original = structuredClone(state.tests[0]);
propose(original,{...original,code:'changed'},'edit','new rule');
assert(state.tests[0].code===original.code,'Pending proposal changed accepted intent');
assert(state.proposals.length===1,'Missing proposal');
assert(!applyDecision(state.proposals[0].id,true,'','reason'),'Accepted anonymous reviewer');
assert(applyDecision(state.proposals[0].id,false,'Reviewer','Preserve rule'),'Could not reject');
assert(state.tests[0].code===original.code,'Rejection changed intent');
propose(state.tests[0],{...state.tests[0],code:'accepted change'},'edit','new requirement');
assert(applyDecision(state.proposals[0].id,true,'Reviewer','Approved requirement'),'Could not approve');
assert(state.tests[0].code==='accepted change'&&state.tests[0].revision===2,'Approved revision not applied');
propose(state.tests[0],{...state.tests[0],classification:'implementation'},'demote','no longer required');
assert(state.tests[0].classification==='intent','Demoted before review');
assert(applyDecision(state.proposals[0].id,true,'Reviewer','Policy updated'),'Could not approve demotion');
assert(state.tests[0].classification==='implementation','Demotion not applied');
state = initial();
propose(state.tests[0],null,'delete','remove requirement');
state.tests[0].revision++;
assert(!applyDecision(state.proposals[0].id,true,'Reviewer','approved'),'Stale approval accepted');
assert(state.tests.length===6,'Stale deletion applied');
applyDecision(state.proposals[0].id,false,'Reviewer','Reject stale proposal');
propose(state.tests[0],null,'delete','remove requirement');
assert(state.tests.length===6,'Deleted before review');
applyDecision(state.proposals[0].id,true,'Reviewer','Requirement removed');
assert(state.tests.length===5,'Approved deletion did not apply');
state = initial();
propose(state.tests[0],{...state.tests[0],path:state.tests[1].path},'edit','rename');
assert(!applyDecision(state.proposals[0].id,true,'Reviewer','approved'),'Duplicate path accepted');
assert(!validPath('../test')&&!validPath('/test')&&!validPath('a/../b'),'Unsafe path accepted');
`,context);
(async()=>{
 vm.runInContext('state=initial(); propose(state.tests[0], {...state.tests[0],code:"pending source"},"edit","proposal");',context);
 const p=await vm.runInContext('policy()',context);
 assert.equal(p.protectedFiles.length,3);
 assert.notEqual(p.protectedFiles[0].code,'pending source');
 assert.equal(p.protectedFiles[0].sha256,require('node:crypto').createHash('sha256').update(p.protectedFiles[0].code).digest('hex'));
 console.log('Review boundary tests passed: pending edits, rejection, approval, demotion, stale revisions, deletion, duplicate paths, baseline hashing.');
})().catch(e=>{console.error(e);process.exitCode=1});
